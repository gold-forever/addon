#!/usr/bin/env bash
# Writes tests/widget_methods.lua: every widget method the client documents (Blizzard's generated API
# documentation, Simple*APIDocumentation.lua), for retail and for WoW: Forever, so the smoke run's
# stand-in client can refuse a method the real one does not have.
#   tools/widget-methods.sh <wow-ui-source live checkout> <wow-ui-source forever checkout>
set -euo pipefail
names() {
  cat "$1"/Interface/AddOns/Blizzard_APIDocumentationGenerated/Simple*APIDocumentation.lua \
    | awk '/Functions =/{f=1} /Events =|Tables =/{f=0} f' \
    | grep -oP '^\t\t\tName = "\K[A-Za-z0-9_]+(?=")' | sort -u
}
out="$(dirname "$0")/../tests/widget_methods.lua"
{
  echo "-- Generated by tools/widget-methods.sh from Gethe/wow-ui-source (Simple*APIDocumentation.lua): the"
  echo "-- widget methods each client documents. The smoke run's stand-in refuses any other method."
  echo "return {"
  for flavour in retail forever; do
    src=$([ "$flavour" = retail ] && echo "$1" || echo "$2")
    echo "  $flavour = {"
    names "$src" | awk '{printf "    %s = true,\n", $0}'
    echo "  },"
  done
  echo "}"
} > "$out"
echo "wrote $out"
